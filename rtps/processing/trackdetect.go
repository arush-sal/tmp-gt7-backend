// Tunable constants for the shape matcher. Conservative starting values; final tuning against real
// captured tracks is Task 8/7, not this task.
const (
	// bboxTolerance widens a candidate's reference bbox (world metres) before the containment test: the
	// driven path is noisy, so requiring EXACT containment would spuriously reject a true match whose
	// noisy positions poke a few metres outside the reference track's boundary bbox. Tuned against the 11
	// real VictoryDash driven laps (Task 8): the worst-case poke of a true track's full-lap driven line
	// past its own RKB affine boundary bbox measured 6.4m (watkins-glen-long; deep-forest-2 5.2m). 10.0m
	// clears that with ~3.6m headroom so the correct candidate survives the pre-filter across the WHOLE
	// lap - not just an early partial-path window - while staying an order of magnitude below the
	// inter-track score separation (correct ~4m vs runner-up >50m), so widening it never admits a wrong
	// winner: it only adds far-away candidates that the shape score + margin gate then reject.
	bboxTolerance = 10.0

	// drivenStride subsamples the accumulated driven path before nearest-neighbour scoring (keep every
	// Nth point), bounding one match attempt's cost to O(len(points)/drivenStride * len(candidate.Points)).
	drivenStride = 5

	// marginRatio is the maximum allowed ratio of the best candidate's score to the second-best's for the
	// match to be declared confident (best/secondBest <= marginRatio): the winner must be clearly better
	// than the runner-up, not just barely ahead, or the two candidates are too similar to distinguish.
	marginRatio = 0.7

	// sanityCap is a loose, boundary-source-agnostic upper bound (world metres) on the winning mean
	// nearest-neighbour score. It exists only to reject "nothing fits" - even a lone surviving candidate
	// is rejected if its fit is this bad.
	sanityCap = 50.0

	// minCoveragePoints is the minimum number of accumulated driven points before any match attempt is
	// made: too little of the lap driven so far cannot reliably distinguish tracks by shape.
	minCoveragePoints = 30

	// reattemptEveryN throttles match attempts to at most once per this many NEWLY accumulated points
	// (not every frame): shape-matching every candidate is comparatively expensive versus one append.
	reattemptEveryN = 15

	// maxPoints bounds the accumulated driven path. Once exceeded, capPoints halves it (keeping every
	// other point) so a long session's memory and per-attempt match cost stay bounded.
	maxPoints = 4000

	// twinGeometryEpsilon is the per-coordinate tolerance (world metres) used to decide whether two
	// candidates' point clouds are the "same" geometry for twin detection. A forward/reverse pair is
	// generated by copying the boundary+corner rows verbatim (see rtps/rkb DetectionGeometry), so a true
	// twin's points match to (near) machine precision; a merely similar but genuinely different layout
	// will not survive this tight a tolerance.
	twinGeometryEpsilon = 1e-6
)

// DetectionGeomProvider is the narrow read-only seam TrackDetector needs from the RKB store: the
// lightweight per-track reference geometry used for live shape matching. Defined here (rather than
// depending on rkb.Store) so TrackDetector only requires what it uses; *rkb.SQLiteStore satisfies
// this structurally, with no import from rkb back into processing.
type DetectionGeomProvider interface {
	DetectionGeometry(ctx context.Context) ([]rkb.TrackGeom, error)
}

// TrackEnricher is the narrow seam TrackDetector needs from the live enrichment state: publishing or
// clearing the correlated track fields for a session. Defined here (rather than depending on the
// concrete *live.EnrichmentState) because rtps/live already imports rtps/processing (for lap/analysis
// types) - depending on rtps/live directly would create an import cycle. *live.EnrichmentState
// satisfies this interface structurally.
type TrackEnricher interface {
	// SetTrack publishes a resolved track match for sessionID.
	SetTrack(sessionID string, slug *string, confidence *string)
	// ClearTrack nils the track fields for sessionID (e.g. on a new session with no match yet).
	ClearTrack(sessionID string)
}

// trackDetectState is the per-session accumulator: the driven path so far (world-metre positions),
// plus a latch so a resolved session stops accumulating/matching once the matcher confirms one.
type trackDetectState struct {
	points  [][2]float64
	latched bool
	// lastAttempt is the point count at the last match attempt, so OnFrame can throttle to at most once
	// per reattemptEveryN newly-accumulated points instead of re-matching on every frame.
	lastAttempt int
}

// TrackDetector implements session.Sink: it accumulates the driven path per session and attempts to
// match it against the RKB's reference track geometry (see matchDecision for the bbox-prefilter +
// shape-match decision).
//
// State is kept per session id (a shared detector may serve concurrent sessions), guarded by a mutex
// since Sink methods are called on each stream's goroutine (mirrors LapSegmenter).
type TrackDetector struct {
	geomProvider DetectionGeomProvider
	enrich       TrackEnricher
	log          *zap.Logger

	mu    sync.Mutex
	state map[string]*trackDetectState

	// geomLoaded and geoms cache the detection geometry after its first (lazy) load: DetectionGeometry
	// assembles every track's reference points in exactly three queries, so it is loaded once per
	// detector lifetime rather than per session.
	geomLoaded bool
	geoms      []rkb.TrackGeom
}

// NewTrackDetector returns a detector that matches driven paths against geom's reference geometry and
// publishes results into enrich. A nil log defaults to zap.NewNop() (matches ingest.NewServer / api
// server / backend wiring convention).
func NewTrackDetector(geom DetectionGeomProvider, enrich TrackEnricher, log *zap.Logger) *TrackDetector {
	if log == nil {
		log = zap.NewNop()
	}
	return &TrackDetector{
		geomProvider: geom,
		enrich:       enrich,
		log:          log,
		state:        make(map[string]*trackDetectState),
	}
}

// OnSessionStart resets fresh accumulation for the session and clears any stale track (a new session
// has not been matched yet, even if the previous one was). It also lazily loads the reference
// geometry on the detector's first use; a load failure is logged and leaves geoms empty, so OnFrame
// simply no-ops the match attempt rather than panicking or retrying every frame.
func (d *TrackDetector) OnSessionStart(rec *session.Record) {
	d.mu.Lock()
	defer d.mu.Unlock()

	d.state[rec.ID] = &trackDetectState{}

	if !d.geomLoaded {
		d.geomLoaded = true // attempt exactly once: a persistent load failure must not retry per session
		geoms, err := d.geomProvider.DetectionGeometry(context.Background())
		if err != nil {
			d.log.Warn("track detection geometry load failed; track detection disabled for this run",
				zap.Error(err))
		} else {
			d.geoms = filterDetectable(geoms)
		}
	}

	d.enrich.ClearTrack(rec.ID)
}

// filterDetectable drops tracks with no reference points (the needs-capture tracks): they can never
// match, so keeping them around would only cost cycles in the per-frame match loop.
func filterDetectable(geoms []rkb.TrackGeom) []rkb.TrackGeom {
	out := make([]rkb.TrackGeom, 0, len(geoms))
	for _, g := range geoms {
		if len(g.Points) == 0 {
			continue
		}
		out = append(out, g)
	}
	return out
}

// OnFrame folds one in-race frame's world position into the session's accumulated path, then - once
// coverage/throttle allow it - attempts a match. Non-in-race frames are ignored (the car is not on
// track). Unknown or already-latched sessions are ignored too.
//
// The match itself runs OUTSIDE d.mu: only the snapshot (points + cached geometry) is taken under the
// lock, which is released before the (comparatively expensive) shape-matching runs. This keeps one
// session's match from serializing every other concurrent session's OnFrame. The lock is re-acquired
// only to commit the latch once a confident result comes back.
func (d *TrackDetector) OnFrame(sessionID string, f *telemetryv1.TelemetryFrame) {
	if !f.GetInRace() {
		return
	}

	d.mu.Lock()
	st := d.state[sessionID]
	if st == nil || st.latched {
		d.mu.Unlock()
		return
	}

	st.points = append(st.points, [2]float64{float64(f.GetPositionX()), float64(f.GetPositionZ())})
	capPoints(st)

	attempt := len(st.points) >= minCoveragePoints && len(st.points)-st.lastAttempt >= reattemptEveryN
	var pointsSnapshot [][2]float64
	var geoms []rkb.TrackGeom
	if attempt {
		st.lastAttempt = len(st.points)
		pointsSnapshot = append([][2]float64(nil), st.points...)
		geoms = d.geoms
	}
	d.mu.Unlock()

	if !attempt {
		return
	}
	d.finishMatch(sessionID, pointsSnapshot, geoms, false)
}

// OnSessionEnd makes a final match attempt with whatever path was accumulated (bypassing the
// reattemptEveryN throttle, but still requiring minCoveragePoints), then drops the session's state
// (nothing further will arrive for it). As with OnFrame, the snapshot is taken under d.mu but the match
// itself runs outside it.
func (d *TrackDetector) OnSessionEnd(rec *session.Record) {
	d.mu.Lock()
	st := d.state[rec.ID]
	attempt := st != nil && !st.latched && len(st.points) >= minCoveragePoints
	var pointsSnapshot [][2]float64
	var geoms []rkb.TrackGeom
	if attempt {
		pointsSnapshot = append([][2]float64(nil), st.points...)
		geoms = d.geoms
	}
	delete(d.state, rec.ID)
	d.mu.Unlock()

	if attempt {
		d.finishMatch(rec.ID, pointsSnapshot, geoms, true)
	}
}

// capPoints halves the accumulated path (keeping every other point) once it exceeds maxPoints, so a
// long session's memory and per-attempt match cost stay bounded rather than growing without limit.
// lastAttempt is halved in step so the reattemptEveryN throttle's point-count arithmetic stays valid
// against the now-shorter slice. Caller must hold d.mu.
func capPoints(st *trackDetectState) {
	if len(st.points) <= maxPoints {
		return
	}
	kept := make([][2]float64, 0, len(st.points)/2+1)
	for i, p := range st.points {
		if i%2 == 0 {
			kept = append(kept, p)
		}
	}
	st.points = kept
	st.lastAttempt /= 2
}

// finishMatch runs matchDecision on a snapshot taken outside d.mu, then - on a confident result -
// commits it: publishes via d.enrich and latches the session. isFinal marks the OnSessionEnd path,
// where the session's state has already been removed from d.state, so there is nothing left to latch
// against and the result is committed unconditionally.
//
// Invariant: Session IDs are never reused within a detector's lifetime (session.Detector's NewID is
// monotonic per instance), so re-checking d.state[sessionID] under the relock is sufficient to
// determine if the session is still valid and unlatch-free: no generation token needed.
func (d *TrackDetector) finishMatch(sessionID string, points [][2]float64, geoms []rkb.TrackGeom, isFinal bool) {
	result := matchDecision(points, geoms)
	if !result.ok {
		return
	}

	if !isFinal {
		d.mu.Lock()
		st := d.state[sessionID]
		if st == nil || st.latched {
			d.mu.Unlock()
			return
		}
		st.latched = true
		d.mu.Unlock()
	}

	slug, confidence := result.slug, result.confidence
	d.enrich.SetTrack(sessionID, &slug, &confidence)
	d.log.Debug("track detected",
		zap.String("session_id", sessionID),
		zap.String("slug", slug))
}

// detectionResult is what matchDecision computes for one match attempt: ok reports whether a confident
// match was found at all, in which case slug/confidence are the values to publish via
// TrackEnricher.SetTrack. confidence is always "confident" for a resolved match, including a
// twin-resolved forward/reverse pair (see forwardReverseTwin): the physical track is identified either
// way, and track detection's job is identifying the track, not the direction of travel.
type detectionResult struct {
	slug       string
	confidence string
	ok         bool
}

// candidateScore is one candidate track's mean nearest-neighbour distance (world metres) against the
// driven path, used to rank candidates inside matchDecision. isReverse/base/points are carried along so a
// tied top-2 can be recognised as a forward/reverse twin (identical geometry, opposite IsReverse, same
// nonzero Base) rather than rejected as ambiguous.
type candidateScore struct {
	slug      string
	score     float64
	isReverse bool
	base      int
	points    [][2]float64
}

// matchDecision runs the bbox containment pre-filter, the nearest-neighbour shape score, and the
// relative-margin decision over one snapshot of the driven path against the reference geometry. It is
// a pure function (no receiver, no lock) so it can run outside d.mu.
func matchDecision(points [][2]float64, geoms []rkb.TrackGeom) detectionResult {
	if len(points) == 0 || len(geoms) == 0 {
		return detectionResult{}
	}

	drivenBbox := computeBbox(points)
	sampled := subsamplePoints(points, drivenStride)

	var candidates []candidateScore
	for _, g := range geoms {
		if g.HasBbox && !bboxContains(drivenBbox, g.Bbox, bboxTolerance) {
			continue // driven path pokes outside this candidate's bbox: cannot be this track
		}
		candidates = append(candidates, candidateScore{
			slug:      g.Slug,
			score:     meanNearestNeighborDistance(sampled, g.Points),
			isReverse: g.IsReverse,
			base:      g.Base,
			points:    g.Points,
		})
	}
	if len(candidates) == 0 {
		return detectionResult{}
	}

	sort.Slice(candidates, func(i, j int) bool { return candidates[i].score < candidates[j].score })

	best := candidates[0]
	if best.score > sanityCap {
		return detectionResult{} // even the best fit is implausibly bad: nothing fits
	}

	if len(candidates) > 1 {
		second := candidates[1]
		// second.score == 0 means the runner-up is an exact match too (an ambiguous tie); reject rather
		// than divide by zero.
		if second.score == 0 || best.score/second.score > marginRatio {
			if twin, ok := forwardReverseTwin(best, second); ok {
				return detectionResult{slug: twin.slug, confidence: "confident", ok: true}
			}
			return detectionResult{} // no clear separation from the runner-up, and not a twin: ambiguous
		}
	}

	return detectionResult{slug: best.slug, confidence: "confident", ok: true}
}

// forwardReverseTwin reports whether a and b are the SAME physical track under two directions: opposite
// IsReverse, the same NONZERO Base, and (near-)identical point clouds (order-insensitive - see
// identicalGeometry). The Base guard exists because geometry alone, once compared as an unordered
// multiset, can no longer rule out two genuinely different layouts that happen to share every point (an
// unobserved-in-the-real-corpus but possible pathological case); requiring a shared, real (nonzero)
// tracks.base pairing keeps that case ambiguous instead of being wrongly resolved as a twin. Two
// different layouts that merely tie on shape score (different geometry, or same Base but different
// points) must stay ambiguous rather than be resolved here. On a twin, the base (IsReverse=false)
// candidate is returned: track detection's job is identifying the physical track, so direction of travel
// never needs to be, and cannot be, disambiguated by this feature.
func forwardReverseTwin(a, b candidateScore) (candidateScore, bool) {
	if a.isReverse == b.isReverse || a.base == 0 || a.base != b.base || !identicalGeometry(a.points, b.points) {
		return candidateScore{}, false
	}
	if a.isReverse {
		return b, true
	}
	return a, true
}

// identicalGeometry reports whether a and b are the same point cloud (the same set of points, up to
// twinGeometryEpsilon per coordinate) regardless of order: same length, then both clouds are copied and
// sorted by (x, then z) before a pairwise tolerance comparison. Order-insensitive because a reverse
// layout's Points is subsampled-boundary ++ apexes (see rtps/rkb DetectionGeometry) where the boundary
// prefix is copied verbatim from the forward twin but the apex suffix is built by reversing the forward's
// corner order (see tools/rkb/rkb/reverse.py _derive_corners) - so a true twin's two point clouds contain
// the same points, but not in the same stored order, and a per-index comparison would wrongly reject it.
func identicalGeometry(a, b [][2]float64) bool {
	if len(a) != len(b) {
		return false
	}
	sa := append([][2]float64(nil), a...)
	sb := append([][2]float64(nil), b...)
	sortPoints(sa)
	sortPoints(sb)
	for i := range sa {
		if math.Abs(sa[i][0]-sb[i][0]) > twinGeometryEpsilon || math.Abs(sa[i][1]-sb[i][1]) > twinGeometryEpsilon {
			return false
		}
	}
	return true
}

// sortPoints sorts points in place by x, then z: the canonical order identicalGeometry compares two
// point clouds under, so the comparison is insensitive to how each cloud is internally ordered.
func sortPoints(points [][2]float64) {
	sort.Slice(points, func(i, j int) bool {
		if points[i][0] != points[j][0] {
			return points[i][0] < points[j][0]
		}
		return points[i][1] < points[j][1]
	})
}

// computeBbox returns [min_x, min_z, max_x, max_z] over points. Caller guarantees points is non-empty.
func computeBbox(points [][2]float64) [4]float64 {
	minX, minZ := points[0][0], points[0][1]
	maxX, maxZ := points[0][0], points[0][1]
	for _, p := range points[1:] {
		minX = math.Min(minX, p[0])
		maxX = math.Max(maxX, p[0])
		minZ = math.Min(minZ, p[1])
		maxZ = math.Max(maxZ, p[1])
	}
	return [4]float64{minX, minZ, maxX, maxZ}
}

// bboxContains reports whether driven sits inside cand, widened by tol on every side: containment, not
// similarity, since a partial driven trace is smaller than the full reference track.
func bboxContains(driven, cand [4]float64, tol float64) bool {
	return driven[0] >= cand[0]-tol && driven[1] >= cand[1]-tol &&
		driven[2] <= cand[2]+tol && driven[3] <= cand[3]+tol
}

// subsamplePoints keeps every stride'th point of points, in order. A stride below 1 is treated as 1
// (no subsampling) rather than looping forever or panicking.
func subsamplePoints(points [][2]float64, stride int) [][2]float64 {
	if stride < 1 {
		stride = 1
	}
	out := make([][2]float64, 0, len(points)/stride+1)
	for i := 0; i < len(points); i += stride {
		out = append(out, points[i])
	}
	return out
}

// meanNearestNeighborDistance scores how well a (subsampled) driven point set is covered by a
// candidate's point cloud: for every point in a, the Euclidean distance to its nearest point in b,
// averaged. Returns +Inf if either set is empty (an empty candidate cannot match anything).
func meanNearestNeighborDistance(a, b [][2]float64) float64 {
	if len(a) == 0 || len(b) == 0 {
		return math.Inf(1)
	}
	var sum float64
	for _, pa := range a {
		best := math.Inf(1)
		for _, pb := range b {
			dx := pa[0] - pb[0]
			dz := pa[1] - pb[1]
			if d := dx*dx + dz*dz; d < best {
				best = d
			}
		}
		sum += math.Sqrt(best)
	}
	return sum / float64(len(a))
}

// PointCountForTest returns the number of accumulated path points for sessionID. Test-only accessor
// (exported so external test packages, needed to avoid an rtps/live<->rtps/processing import cycle,
// can assert accumulation without reaching into unexported state).
func (d *TrackDetector) PointCountForTest(sessionID string) int {
	d.mu.Lock()
	defer d.mu.Unlock()
	st := d.state[sessionID]
	if st == nil {
		return 0
	}
	return len(st.points)
}
