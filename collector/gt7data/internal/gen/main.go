// Command gen reads carlist.csv and regenerates carnames_gen.go, the compiled GT7 car-id -> name
// table. Run it via `go generate ./collector/gt7data`. It fails loud on any data anomaly (bad id,
// empty/padded/non-UTF-8 name, duplicate id, or two names that would resolve to the same display
// string) so a malformed source can never silently ship a wrong table.
package main

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	inputCSV   = "carlist.csv"     // read relative to the gt7data package dir (go:generate cwd)
	outputFile = "carnames_gen.go" // written into the gt7data package dir
)

func main() {
	f, err := os.Open(inputCSV)
	if err != nil {
		fatal(err)
	}
	defer func() { _ = f.Close() }()

	rows, err := parseCSV(f)
	if err != nil {
		fatal(err)
	}
	names, err := resolve(rows)
	if err != nil {
		fatal(err)
	}
	src, err := emitSource(names)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(outputFile, src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %s (%d cars)\n", outputFile, len(names))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

// emitSource renders the id->name map as gofmt-clean Go source for package gt7data. Entries are
// sorted by ascending id so regeneration is deterministic (no map-iteration churn in diffs). Names
// are written with strconv.Quote to produce correct Go string literals for any UTF-8 content.
func emitSource(names map[int32]string) ([]byte, error) {
	ids := make([]int, 0, len(names))
	for id := range names {
		ids = append(ids, int(id))
	}
	sort.Ints(ids)

	var b strings.Builder
	b.WriteString("// Code generated by collector/gt7data/internal/gen; DO NOT EDIT.\n\n")
	b.WriteString("package gt7data\n\n")
	b.WriteString("// carNames maps a GT7 car model id to its display name. A car with a unique base\n")
	b.WriteString("// name has its model year dropped; cars sharing a base keep the year to disambiguate.\n")
	b.WriteString("// Generated from carlist.csv by `go generate ./collector/gt7data`.\n")
	b.WriteString("var carNames = map[int32]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%d: %s,\n", id, strconv.Quote(names[int32(id)]))
	}
	b.WriteString("}\n")

	return format.Source([]byte(b.String()))
}
